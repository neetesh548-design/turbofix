let registered = false;

/** Idempotently merges the verification keys into the global i18n manager. */
export function registerVerificationTranslations(): void {
  if (registered) return;
  Object.entries(VERIFICATION_TRANSLATIONS).forEach(([language, dictionary]) => {
    i18n.addTranslations(language, dictionary);
  });
  registered = true;
}

// Register on import so any component that pulls in the feature gets the keys.
registerVerificationTranslations();

export type TranslateFn = (key: string, params?: Record<string, string | number>) => string;

/**
 * `t` with an English fallback. The base i18n manager echoes the key back when
 * a language lacks an entry; here we drop to English first so the UI never
 * shows a raw dotted key.
 */
export function useVerificationT(): { t: TranslateFn; isRTL: boolean; language: string } {
  const { t: baseT, language, isRTL } = useI18n();

  const t = useCallback<TranslateFn>(
    (key, params) => {
      const translated = baseT(key, params);
      if (translated !== key) return translated;
      const fallback = en[key];
      if (!fallback) return key;
      return fallback.replace(/\{(\w+)\}/g, (match, param: string) => {
        const value = params?.[param];
        return value === undefined || value === null ? match : String(value);
      });
    },
    [baseT],
  );

  return { t, isRTL: isRTL(), language };
}

